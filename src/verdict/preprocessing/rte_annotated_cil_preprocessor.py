"""RTE-annotated CIL file generator via Frama-C.

Runs `frama-c -rte -then -print` on a C source file to produce
a CIL file with RTE assertions (e.g. /*@ assert rte_1: ... */).

Adapted from reference_implementation/preprocessing/rte_annotated_cil_preprocessor.py.
"""

from __future__ import annotations

import logging
import os
from typing import List

from verdict.framac.runner import FramaCRunner

logger = logging.getLogger(__name__)


class RTEAnnotatedCILPreprocessor:
    """Generate RTE-annotated CIL file from a C source using Frama-C."""

    def __init__(
        self,
        source_file_path: str,
        rte_assertion_type: str = "rte",
        eva_parameters: List[str] | None = None,
    ) -> None:
        self.source_file_path = source_file_path
        self.annotated_cil_file_path = source_file_path.replace(
            ".c", f"_{rte_assertion_type}_annotated_cil.c"
        )
        self.frama_c_runner = FramaCRunner(source_file_path)
        self.rte_assertion_type = rte_assertion_type
        self.eva_parameters = eva_parameters or []
        self.commands = self._setup_commands()

    def _setup_commands(self) -> List[str]:
        if self.rte_assertion_type == "rte":
            return ["-rte", "-then", "-print"]
        elif self.rte_assertion_type == "Eva":
            cmds = ["-eva", "-eva-warn-undefined-pointer-comparison", "none"]
            cmds.extend(self.eva_parameters)
            cmds.extend(["-then", "-print"])
            return cmds
        else:
            raise ValueError(f"Unsupported assertion type: {self.rte_assertion_type}")

    def generate_annotated_cil(self) -> bool:
        """Generate annotated CIL file. Returns True on success."""
        success, output = self.frama_c_runner.run_FramaC(self.commands)
        if not success:
            logger.error("Frama-C execution failed: %s", output[:500])
            return False

        code_marker = "/* Generated by Frama-C */"
        code_start = output.find(code_marker)
        if code_start == -1:
            logger.error("Could not find Frama-C code marker in output")
            return False

        code_content = output[code_start:]
        with open(self.annotated_cil_file_path, "w") as f:
            f.write(code_content)

        logger.info("Annotated CIL file generated at %s", self.annotated_cil_file_path)
        return True
