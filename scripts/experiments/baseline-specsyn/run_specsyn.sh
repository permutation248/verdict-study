#!/usr/bin/env bash
# Run the SpecSyn baseline pipeline on ONE Verdict benchmark input.
#
#   run_specsyn.sh <bench> [model] [rep]
#   run_specsyn.sh student-enrollment claude-sonnet-4-6 1
#
# Runs the SpecSyn pipeline against one prepared benchmark input. Stages a
# fresh copy of the pipeline, swaps in api_anthropic.py (the single patched
# file), runs main.py on the prepared input, then scores the restored
# annotated file under BOTH WP presets.
#
# Prerequisites on the run host:
#   - the SpecSyn artifact at $SPECSYN_ARTIFACT (default $HOME/SpecSyn-Artifact-main)
#   - a python venv with: pycparser==2.22 anthropic psutil
#     (default $SPECSYN_VENV = $HOME/SpecSyn-Artifact-main/.venv)
#   - frama-c on PATH
#   - inputs generated by prepare_inputs.py and present in the repo at
#     scripts/experiments/baseline-specsyn/inputs/<bench>/

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"

bench="${1:?usage: run_specsyn.sh <bench> [model] [rep]}"
model="${2:-claude-sonnet-4-6}"
rep="${3:-1}"

ARTIFACT="${SPECSYN_ARTIFACT:-$HOME/SpecSyn-Artifact-main}"
VENV="${SPECSYN_VENV:-$HOME/SpecSyn-Artifact-main/.venv}"

in_dir="$SCRIPT_DIR/inputs/$bench"
input="$(ls "$in_dir"/*.c 2>/dev/null | head -1)"
[ -n "$input" ] || { echo "no prepared input for $bench — run prepare_inputs.py first" >&2; exit 2; }
[ -d "$ARTIFACT" ] || { echo "artifact not found: $ARTIFACT" >&2; exit 2; }
[ -x "$VENV/bin/python3" ] || { echo "venv missing: $VENV" >&2; exit 2; }
command -v frama-c >/dev/null || { echo "frama-c not on PATH (opam switch fc29?)" >&2; exit 2; }

# API config from the repo .env (anthropic-format endpoint; the adapter
# reads ANTHROPIC_API_KEY / ANTHROPIC_BASE_URL / SPECSYN_MODEL).
export ANTHROPIC_API_KEY="$(grep -m1 '^ANTHROPIC_API_KEY=' "$ROOT/.env" | cut -d= -f2)"
export ANTHROPIC_BASE_URL="$(grep -m1 '^ANTHROPIC_BASE_URL=' "$ROOT/.env" | cut -d= -f2)"
[ -n "$ANTHROPIC_API_KEY" ] || { echo "no ANTHROPIC_API_KEY in $ROOT/.env" >&2; exit 2; }
export SPECSYN_MODEL="$model"

out="$ROOT/scripts/experiments/results/baseline-specsyn/$bench/$model/rep$rep"
if [ -e "$out/DONE" ]; then
  echo "SKIP $bench model=$model rep=$rep (already DONE: $out)"
  exit 0
fi
if [ -d "$out" ] && [ -n "$(ls -A "$out" 2>/dev/null)" ]; then
  mv "$out" "${out}.partial_$(date +%Y%m%d_%H%M%S)"
fi
mkdir -p "$out"

# ── Stage a fresh copy of the pipeline ──
work="$out/pipeline"
mkdir -p "$work"
for f in main.py algo.py decomp.py prompt.py verifier.py metric.py \
         utils.py files.py settings.py restore.py equiv.py mutate.py; do
  cp "$ARTIFACT/$f" "$work/" || { echo "artifact file missing: $f" >&2; exit 2; }
done
cp -r "$ARTIFACT/pycparser" "$work/pycparser"
mkdir -p "$work"/{logs,output,tmp}
# The single patch: our anthropic adapter replaces api.py wholesale.
cp "$SCRIPT_DIR/api_anthropic.py" "$work/api.py"

cp "$input" "$out/input.c"

# ── Sanity gates (cheap, before any LLM spend) ──
( cd "$work" && "$VENV/bin/python3" - "$out/input.c" <<'PYEOF'
import sys
from decomp import parse_file  # noqa: F401  (import = deps present)
import decomp
ast = decomp.parse_file(sys.argv[1], use_cpp=True,
                        cpp_args=r"-I./pycparser/utils/fake_libc_include")
print(f"decomp parse OK: {len(ast.ext)} top-level decls")
PYEOF
) || { echo "decomp parse gate FAILED" >&2; exit 2; }

"$VENV/bin/python3" -c "import anthropic; print('anthropic', anthropic.__version__)" || exit 2

# ── WP no-init shim (scoped to the pipeline run only) ──
# Their verifier.py hardcodes `frama-c -wp ... -wp-model Typed+var+int+real`;
# a PATH-precedent wrapper injects -wp-no-init-const to match Verdict's
# _wp_core() (const-global initial values must be proven, not assumed).
# Scoped via env on the main.py invocation so the decomp gate and the
# post-run scoring below keep their own semantics.
# Override: SPECSYN_WP_NOINIT=0 disables injection (e.g. for x509 benches
# where const-table init assumptions match the tools' original semantics).
SPECSYN_WP_NOINIT="${SPECSYN_WP_NOINIT:-1}"

SHIM_EXTRA_PATH=""
SHIM_ENV=""
if [ "$SPECSYN_WP_NOINIT" = "1" ]; then
  SHIM_DIR="$out/.wp-shim"
  mkdir -p "$SHIM_DIR"
  cp "$ROOT/scripts/experiments/baseline-preguss/docker/framac-wpmodel-wrapper.sh" "$SHIM_DIR/frama-c"
  chmod +x "$SHIM_DIR/frama-c"
  REAL_FC="$(command -v frama-c)"
  SHIM_EXTRA_PATH="$SHIM_DIR:"
  SHIM_ENV="REAL_FRAMAC=$REAL_FC PREGUSS_WP_NOINIT=1"
fi

SPECSYN_TIMEOUT="${SPECSYN_TIMEOUT:-86400}"

# ── Run (hours; caller should nohup this script) ──
echo "specsyn: bench=$bench model=$model rep=$rep input=$(basename "$input") wp_noinit=$SPECSYN_WP_NOINIT timeout=${SPECSYN_TIMEOUT}s"
start_epoch=$(date +%s)
timeout "${SPECSYN_TIMEOUT}s" \
  bash -c "cd \"$work\" && export PATH=\"${SHIM_EXTRA_PATH}\$PATH\"
  [ -n \"$SHIM_EXTRA_PATH\" ] && export REAL_FRAMAC=\"$REAL_FC\" PREGUSS_WP_NOINIT=1
  \"$VENV/bin/python3\" ./main.py --file \"$out/input.c\"" \
  > "$out/specsyn.log" 2>&1
rc=$?
end_epoch=$(date +%s)

# Outputs: per-module spec json + restored annotated .c. Their main.py never
# invokes restore.py (verified 2026-06-12 on both x509 submodules) — restoring
# the annotated source from the spec json is OUR step.
cp -r "$work/output" "$out/output" 2>/dev/null || true
annotated="$(ls "$work"/output/*.c 2>/dev/null | head -1)"
if [ -z "$annotated" ] && [ -f "$work/output/input.json" ]; then
  ( cd "$work" && "$VENV/bin/python3" ./restore.py --file output/input.json ) \
    > "$out/output/restored.annotated.c" \
    && annotated="$out/output/restored.annotated.c"
fi

{
  echo "bench=$bench model=$model rep=$rep host=$(hostname)"
  echo "artifact=$ARTIFACT"
  echo "rc=$rc wall_min=$(awk "BEGIN{printf \"%.2f\", ($end_epoch-$start_epoch)/60}")"
  echo "input=$(basename "$input") annotated=${annotated:-none}"
  echo "wp_noinit_injected=$SPECSYN_WP_NOINIT"
} > "$out/provenance.txt"

# ── Score under both WP presets (their semantics + our sound semantics) ──
if [ -n "$annotated" ]; then
  "$VENV/bin/python3" "$SCRIPT_DIR/score_rte.py" "$annotated" \
    --preset specsyn --csv "$out/score_specsyn_preset.csv" || true
  "$VENV/bin/python3" "$SCRIPT_DIR/score_rte.py" "$annotated" \
    --preset verdict --csv "$out/score_verdict_preset.csv" || true
else
  echo "no annotated output produced — see specsyn.log" >&2
fi

if [ $rc -eq 124 ]; then
  echo "specsyn: TIMEOUT after ${SPECSYN_TIMEOUT}s — preserving partial results"
  echo "timeout=${SPECSYN_TIMEOUT}s" >> "$out/provenance.txt"
fi
[ $rc -eq 0 ] || [ $rc -eq 124 ] && touch "$out/DONE"
echo "specsyn: rc=$rc -> $out"
exit $rc
